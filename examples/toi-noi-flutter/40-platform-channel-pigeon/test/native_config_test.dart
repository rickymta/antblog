// Các file Kotlin và Swift trong native-config/ không được biên dịch ở đây
// (máy này không có Android SDK và Xcode đầy đủ). Test này chỉ đọc chúng và
// kiểm những chuỗi mà hai phía phải khớp nhau: tên channel, tên method, mã lỗi,
// luồng gọi, tên channel do Pigeon sinh.
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:toi_noi_40/toi_noi_40.dart';
import 'package:yaml/yaml.dart';

const String _kotlinDir =
    'native-config/android/app/src/main/kotlin/vn/toinoi/toi_noi_40';
const String _swiftDir = 'native-config/ios/Runner';

String _read(String path) => File(path).readAsStringSync();

void main() {
  late String kChannel;
  late String kReader;
  late String kMain;
  late String kPigeon;
  late String sChannel;
  late String sReader;
  late String sApp;
  late String sPigeon;

  setUpAll(() {
    kChannel = _read('$_kotlinDir/MethodChannelBattery.kt');
    kReader = _read('$_kotlinDir/BatteryReader.kt');
    kMain = _read('$_kotlinDir/MainActivity.kt');
    kPigeon = _read('$_kotlinDir/PigeonBattery.kt');
    sChannel = _read('$_swiftDir/MethodChannelBattery.swift');
    sReader = _read('$_swiftDir/BatteryReader.swift');
    sApp = _read('$_swiftDir/AppDelegate.swift');
    sPigeon = _read('$_swiftDir/PigeonBattery.swift');
  });

  group('MethodChannel viết tay: Dart, Kotlin và Swift cùng một hợp đồng', () {
    test('tên channel khớp từng ký tự', () {
      expect(kChannel, contains('"$batteryChannelName"'));
      expect(sChannel, contains('"$batteryChannelName"'));
    });

    test('tên method hai chiều khớp', () {
      for (final source in [kChannel, sChannel]) {
        expect(source, contains('"$getBatteryStatusMethod"'));
        expect(source, contains('"$onBatteryChangedMethod"'));
      }
    });

    test('method lạ trả "chưa cài đặt", pin không có trả UNAVAILABLE', () {
      expect(kChannel, contains('result.notImplemented()'));
      expect(kChannel, contains('result.error("UNAVAILABLE"'));
      expect(sChannel, contains('FlutterMethodNotImplemented'));
      expect(sChannel, contains('code: "UNAVAILABLE"'));
    });

    test('khoá của Map khớp BatteryStatus.toMap', () {
      final keys = const BatteryStatus(
        levelPercent: 1,
        isCharging: false,
        isPowerSaveMode: false,
      ).toMap().keys;
      for (final key in keys) {
        expect(kChannel, contains('"$key"'));
        expect(sChannel, contains('"$key"'));
      }
    });
  });

  group('Pigeon: ba file sinh ra cùng một phiên bản và cùng tên channel', () {
    const generated = [
      'lib/src/generated/battery_api.g.dart',
      '$_kotlinDir/BatteryApi.g.kt',
      '$_swiftDir/BatteryApi.g.swift',
    ];

    test('cùng phiên bản pigeon, khớp ràng buộc trong pubspec.yaml', () {
      final pubspec = loadYaml(_read('pubspec.yaml')) as YamlMap;
      final constraint =
          (pubspec['dev_dependencies'] as YamlMap)['pigeon'] as String;
      final versions = generated
          .map(
            (path) =>
                RegExp(r'Autogenerated from Pigeon \(v([\d.]+)\)')
                    .firstMatch(_read(path))!
                    .group(1),
          )
          .toSet();
      expect(
        versions,
        hasLength(1),
        reason: 'file sinh từ hai lần chạy khác nhau',
      );
      expect(constraint, '^${versions.single}');
    });

    test('tên channel của HostApi và FlutterApi giống nhau ở cả ba file', () {
      for (final name in [
        'dev.flutter.pigeon.toi_noi_40.BatteryHostApi.getBatteryStatus',
        'dev.flutter.pigeon.toi_noi_40.BatteryFlutterApi.onBatteryChanged',
      ]) {
        for (final path in generated) {
          expect(_read(path), contains(name), reason: path);
        }
      }
    });

    test(
      'FlutterApi dùng callback, nên Kotlin không cần kotlinx-coroutines',
      () {
        final kotlin = _read('$_kotlinDir/BatteryApi.g.kt');
        expect(kotlin, contains('callback: (Result<Unit>) -> Unit'));
        expect(kotlin, isNot(contains('suspend fun')));
        expect(kotlin, isNot(contains('kotlinx.coroutines')));
      },
    );

    test('package Kotlin khớp thư mục và khớp applicationId của project', () {
      for (final source in [
        kReader,
        kMain,
        kPigeon,
        kChannel,
        _read('$_kotlinDir/BatteryApi.g.kt'),
      ]) {
        expect(
          RegExp(
            r'^package vn\.toinoi\.toi_noi_40$',
            multiLine: true,
          ).hasMatch(source),
          isTrue,
        );
      }
    });
  });

  group('luồng gọi và vòng đời', () {
    test('Android: nghe cả đổi pin và đổi chế độ tiết kiệm pin, receiver không export', () {
      expect(kMain, contains('Intent.ACTION_BATTERY_CHANGED'));
      expect(kMain, contains('PowerManager.ACTION_POWER_SAVE_MODE_CHANGED'));
      expect(kMain, contains('ContextCompat.RECEIVER_NOT_EXPORTED'));
      expect(kMain, contains('unregisterReceiver'));
    });

    test(
      'Android: đọc pin bằng BatteryManager và PowerManager, không cần quyền',
      () {
        expect(kReader, contains('BATTERY_PROPERTY_CAPACITY'));
        expect(kReader, contains('isPowerSaveMode'));
        expect(
          Directory('native-config/android')
              .listSync(recursive: true)
              .whereType<File>()
              .where((f) => f.path.endsWith('AndroidManifest.xml')),
          isEmpty,
          reason: 'lab không sửa manifest vì đọc pin không cần quyền',
        );
      },
    );

    test(
      'Android: cả hai cầu được đăng ký trên binaryMessenger của engine',
      () {
        expect(kMain, contains('flutterEngine.dartExecutor.binaryMessenger'));
        expect(kMain, contains('MethodChannelBattery(reader, messenger)'));
        expect(kMain, contains('PigeonBattery(reader, messenger)'));
        expect(kPigeon, contains('BatteryHostApi.setUp(messenger, this)'));
      },
    );

    test(
      'iOS: messenger lấy từ engineBridge (UIScene), cầu được giữ tham chiếu',
      () {
        expect(sApp, contains('FlutterImplicitEngineDelegate'));
        expect(
          sApp,
          contains(
            'GeneratedPluginRegistrant.register(with: engineBridge.pluginRegistry)',
          ),
        );
        expect(sApp, contains('engineBridge.applicationRegistrar.messenger()'));
        expect(sApp, contains('private var methodChannelBattery'));
        expect(sApp, contains('private var pigeonBattery'));
      },
    );

    test(
      'iOS: nghe đổi mức pin, trạng thái sạc và Low Power Mode trên main queue',
      () {
        for (final name in [
          'UIDevice.batteryLevelDidChangeNotification',
          'UIDevice.batteryStateDidChangeNotification',
          'Notification.Name.NSProcessInfoPowerStateDidChange',
        ]) {
          expect(sApp, contains(name));
        }
        expect(sApp, contains('queue: .main'));
        expect(sReader, contains('isLowPowerModeEnabled'));
        expect(sReader, contains('batteryState == .unknown'));
        expect(sPigeon, contains('BatteryHostApiSetup.setUp'));
      },
    );
  });
}

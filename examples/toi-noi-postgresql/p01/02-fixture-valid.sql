-- Kiểm nhanh: số chuyến theo loại và trạng thái (8 trạng thái đều có mặt).
SELECT status,
       count(*) FILTER (WHERE kind = 'ride')   AS ride,
       count(*) FILTER (WHERE kind = 'food')   AS food,
       count(*) FILTER (WHERE kind = 'parcel') AS parcel,
       count(*)                                AS tong
FROM trips
GROUP BY status
ORDER BY array_position(
  ARRAY['requested', 'searching', 'accepted', 'arriving', 'picked_up', 'in_transit', 'completed', 'cancelled'],
  status);
